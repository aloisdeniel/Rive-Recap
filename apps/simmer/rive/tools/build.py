#!/usr/bin/env python3
"""Generate the Simmer recap RML.

    python3 tools/build.py                      # writes scenes/*.rml + data/user-recap.rml
    python3 tools/build.py --fixture=extreme.json --out=<dir>   # variant data file only

The generated .rml files are the editable source the CLI compiles; this
script is how they were authored (art, timelines and state machines are
parameterised here so all ten scenes stay consistent).
"""
import os
import sys
import argparse

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rml
from rml import E
import data
from data import load_fixture, instance, view_model, assets, CONVERTERS
import pot
import main_board
import scenes

ROOT = data.ROOT


def wrap(*els):
    doc = E('Rive', version='1', kind='fragment', id=None)
    doc.attrs.pop('id', None)
    doc.add(*els)
    return '<!-- GENERATED by tools/build.py -- edit the generator, then rebuild -->\n' + doc.xml() + '\n'


def write(path, content):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        f.write(content)


def data_doc(fixture_names):
    rml.reset_ids(100000)
    insts = []
    ids = ['0:401', '0:402', '0:403', '0:404']
    for i, (inst_name, fx) in enumerate(fixture_names):
        insts.append(instance(inst_name, load_fixture(fx), ids[i]))
    return wrap(view_model(insts), *assets())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--first', default='fixture.json')
    ap.add_argument('--out', default=ROOT)
    args = ap.parse_args()

    fixtures = [('Fixture', 'fixture.json'), ('New user', 'new-user.json'), ('Extreme', 'extreme.json')]
    first = [f for f in fixtures if f[1] == args.first]
    rest = [f for f in fixtures if f[1] != args.first]
    write(os.path.join(args.out, 'data', 'user-recap.rml'), data_doc(first + rest))

    rml.reset_ids(1000)
    E.__init__.__defaults__  # noqa
    scene_boards = []
    scene_objs = []
    for k in range(1, 11):
        sc = scenes.build_scene(k, x_stage=500 + (k - 1) * 440)
        ab = sc.build()
        scene_objs.append(sc)
        sm = [c for c in ab.children if c.tag == 'StateMachine'][0]
        scene_boards.append((ab, sm))
    pot_ab, pot_sm = pot.build_pot(500)
    main_ab = main_board.build_main(scene_boards, pot_ab, pot_sm, x_stage=0)
    extra_boards = scenes.extra_components()

    write(os.path.join(args.out, 'scenes', 'main.rml'), wrap(main_ab))
    write(os.path.join(args.out, 'scenes', 'scenes.rml'), wrap(*[ab for ab, _ in scene_boards], *[s.component_asset() for s in scene_objs]))
    write(os.path.join(args.out, 'scenes', 'components.rml'),
          wrap(pot_ab, E('ComponentAsset', artboardId=pot_ab.id, name='Pot motif'),
               *[b for b, _ in extra_boards], *[E('ComponentAsset', artboardId=b.id, name=b.attrs['name']) for b, _ in extra_boards]))
    write(os.path.join(args.out, 'scenes', 'converters.rml'), wrap(*CONVERTERS))
    print('generated', len(CONVERTERS), 'converters')


if __name__ == '__main__':
    main()
